export const allTopics = chapters.flatMap((chapter) =>
  chapter.topics.map((topic) => ({ ...topic, chapter }))
);

export function topicHref(chapterSlug: string, topicSlug: string) {
  return `/learn/curriculum/${chapterSlug}/${topicSlug}/`;
}

export function findTopicByPath(pathname: string) {
  const normalized = pathname.endsWith("/") ? pathname : `${pathname}/`;
  return allTopics.find(({ chapter, slug }) =>
    normalized === topicHref(chapter.slug, slug)
  );
}
